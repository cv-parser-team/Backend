import { describe, expect, it, vi } from 'vitest';
import type { MessageBroker } from '../../infrastructure/messaging/message-broker.js';
import type {
  DocumentProcessingRepository,
  ProcessingJobRecord
} from './document-processing.repository.js';
import { createDocumentProcessingService } from './document-processing.service.js';
import { PARSE_DOCUMENT_QUEUE } from './parse-document.job.js';

const documentId = '22222222-2222-4222-8222-222222222222';
const jobId = '11111111-1111-4111-8111-111111111111';

function createJobRecord(
  overrides: Partial<ProcessingJobRecord> = {}
): ProcessingJobRecord {
  return {
    jobId,
    documentId,
    status: 'queued',
    attemptCount: 0,
    failureCode: null,
    availableAt: new Date('2026-01-01T00:00:00.000Z'),
    lockedUntil: null,
    createdAt: new Date('2026-01-01T00:00:00.000Z'),
    updatedAt: new Date('2026-01-01T00:00:00.000Z'),
    ...overrides
  };
}

function createRepositoryDouble(
  record: ProcessingJobRecord = createJobRecord(),
  overrides: Partial<DocumentProcessingRepository> = {}
): DocumentProcessingRepository {
  return {
    createQueuedJob: vi.fn().mockResolvedValue(record),
    claimJob: vi.fn().mockResolvedValue(null),
    completeJob: vi.fn().mockResolvedValue(null),
    failJob: vi.fn().mockResolvedValue(null),
    listPublishableJobs: vi.fn().mockResolvedValue([]),
    ...overrides
  };
}

function createBrokerDouble(): MessageBroker {
  return {
    publish: vi.fn().mockResolvedValue(undefined)
  };
}

describe('document processing service', () => {
  it('creates one durable queued job for the document', async () => {
    const repository = createRepositoryDouble();
    const service = createDocumentProcessingService({
      broker: createBrokerDouble(),
      repository
    });

    await service.schedule(documentId);

    expect(repository.createQueuedJob).toHaveBeenCalledOnce();
    expect(repository.createQueuedJob).toHaveBeenCalledWith(documentId);
  });

  it('returns only the versioned queue message fields', async () => {
    const service = createDocumentProcessingService({
      broker: createBrokerDouble(),
      repository: createRepositoryDouble()
    });

    const message = await service.schedule(documentId);

    expect(message).toEqual({
      version: 1,
      jobId,
      documentId
    });
    expect(Object.keys(message)).toEqual(['version', 'jobId', 'documentId']);
  });

  it('uses the job ID generated by persistence', async () => {
    const generatedJobId = '33333333-3333-4333-8333-333333333333';
    const service = createDocumentProcessingService({
      broker: createBrokerDouble(),
      repository: createRepositoryDouble(
        createJobRecord({ jobId: generatedJobId })
      )
    });

    await expect(service.schedule(documentId)).resolves.toMatchObject({
      jobId: generatedJobId
    });
  });

  it('publishes the minimal job after it is persisted', async () => {
    const operations: string[] = [];
    const repository = createRepositoryDouble(createJobRecord(), {
      createQueuedJob: vi.fn(async () => {
        operations.push('persist');
        return createJobRecord();
      })
    });
    const broker: MessageBroker = {
      publish: vi.fn(async () => {
        operations.push('publish');
      })
    };
    const service = createDocumentProcessingService({ broker, repository });

    await service.schedule(documentId);

    expect(operations).toEqual(['persist', 'publish']);
    expect(broker.publish).toHaveBeenCalledWith(PARSE_DOCUMENT_QUEUE, {
      version: 1,
      jobId,
      documentId
    });
  });

  it('does not publish when persistence fails', async () => {
    const failure = new Error('database unavailable');
    const repository = createRepositoryDouble(createJobRecord(), {
      createQueuedJob: vi.fn().mockRejectedValue(failure)
    });
    const broker = createBrokerDouble();
    const service = createDocumentProcessingService({ broker, repository });

    await expect(service.schedule(documentId)).rejects.toBe(failure);
    expect(repository.createQueuedJob).toHaveBeenCalledOnce();
    expect(broker.publish).not.toHaveBeenCalled();
  });

  it('propagates publication failures without creating another job', async () => {
    const failure = new Error('broker unavailable');
    const repository = createRepositoryDouble();
    const broker: MessageBroker = {
      publish: vi.fn().mockRejectedValue(failure)
    };
    const service = createDocumentProcessingService({ broker, repository });

    await expect(service.schedule(documentId)).rejects.toBe(failure);
    expect(repository.createQueuedJob).toHaveBeenCalledOnce();
    expect(broker.publish).toHaveBeenCalledOnce();
  });

  it('claims the delivered job with the initial processing lease', async () => {
    const claimedJob = createJobRecord({
      status: 'processing',
      attemptCount: 1,
      lockedUntil: new Date('2026-01-01T00:05:00.000Z')
    });
    const repository = createRepositoryDouble(createJobRecord(), {
      claimJob: vi.fn().mockResolvedValue(claimedJob)
    });
    const service = createDocumentProcessingService({
      broker: createBrokerDouble(),
      repository
    });

    await expect(
      service.claim({ version: 1, jobId, documentId })
    ).resolves.toBe(claimedJob);
    expect(repository.claimJob).toHaveBeenCalledWith({
      jobId,
      documentId,
      leaseMilliseconds: 300_000
    });
  });

  it('returns null when a delivered job cannot be claimed', async () => {
    const repository = createRepositoryDouble();
    const service = createDocumentProcessingService({
      broker: createBrokerDouble(),
      repository
    });

    await expect(
      service.claim({ version: 1, jobId, documentId })
    ).resolves.toBeNull();
  });

  it('completes a processing job and clears its lease', async () => {
    const completedJob = createJobRecord({
      status: 'completed',
      attemptCount: 1,
      lockedUntil: null
    });
    const repository = createRepositoryDouble(createJobRecord(), {
      completeJob: vi.fn().mockResolvedValue(completedJob)
    });
    const service = createDocumentProcessingService({
      broker: createBrokerDouble(),
      repository
    });

    await expect(
      service.complete({ version: 1, jobId, documentId })
    ).resolves.toBe(completedJob);
    expect(repository.completeJob).toHaveBeenCalledWith({ jobId, documentId });
  });

  it('returns null when a processing job cannot be completed', async () => {
    const repository = createRepositoryDouble();
    const service = createDocumentProcessingService({
      broker: createBrokerDouble(),
      repository
    });

    await expect(
      service.complete({ version: 1, jobId, documentId })
    ).resolves.toBeNull();
  });

  it('fails a processing job and clears its lease', async () => {
    const failedJob = createJobRecord({
      status: 'failed',
      attemptCount: 1,
      failureCode: 'PARSING_FAILED',
      lockedUntil: null
    });
    const repository = createRepositoryDouble(createJobRecord(), {
      failJob: vi.fn().mockResolvedValue(failedJob)
    });
    const service = createDocumentProcessingService({
      broker: createBrokerDouble(),
      repository
    });

    await expect(
      service.fail({ version: 1, jobId, documentId }, ' PARSING_FAILED ')
    ).resolves.toBe(failedJob);
    expect(repository.failJob).toHaveBeenCalledWith({
      jobId,
      documentId,
      failureCode: 'PARSING_FAILED'
    });
  });

  it('returns null when a processing job cannot be failed', async () => {
    const repository = createRepositoryDouble();
    const service = createDocumentProcessingService({
      broker: createBrokerDouble(),
      repository
    });

    await expect(
      service.fail({ version: 1, jobId, documentId }, 'PARSING_FAILED')
    ).resolves.toBeNull();
  });

  it('rejects an empty processing job failure code', async () => {
    const repository = createRepositoryDouble();
    const service = createDocumentProcessingService({
      broker: createBrokerDouble(),
      repository
    });

    await expect(
      service.fail({ version: 1, jobId, documentId }, '  ')
    ).rejects.toThrow('Processing job failure code is required');
    expect(repository.failJob).not.toHaveBeenCalled();
  });

  it('republishes one bounded batch using existing job IDs', async () => {
    const secondJob = createJobRecord({
      jobId: '33333333-3333-4333-8333-333333333333',
      documentId: '44444444-4444-4444-8444-444444444444'
    });
    const repository = createRepositoryDouble(createJobRecord(), {
      listPublishableJobs: vi
        .fn()
        .mockResolvedValue([createJobRecord(), secondJob])
    });
    const broker = createBrokerDouble();
    const service = createDocumentProcessingService({ broker, repository });

    await expect(service.republishQueuedJobs()).resolves.toEqual({
      published: 2,
      failures: []
    });
    expect(repository.listPublishableJobs).toHaveBeenCalledWith(
      expect.any(Date),
      100
    );
    expect(repository.createQueuedJob).not.toHaveBeenCalled();
    expect(broker.publish).toHaveBeenNthCalledWith(1, PARSE_DOCUMENT_QUEUE, {
      version: 1,
      jobId,
      documentId
    });
    expect(broker.publish).toHaveBeenNthCalledWith(2, PARSE_DOCUMENT_QUEUE, {
      version: 1,
      jobId: secondJob.jobId,
      documentId: secondJob.documentId
    });
  });

  it('continues republishing after an individual failure', async () => {
    const failure = new Error('broker unavailable');
    const secondJob = createJobRecord({
      jobId: '33333333-3333-4333-8333-333333333333'
    });
    const repository = createRepositoryDouble(createJobRecord(), {
      listPublishableJobs: vi
        .fn()
        .mockResolvedValue([createJobRecord(), secondJob])
    });
    const broker: MessageBroker = {
      publish: vi
        .fn()
        .mockRejectedValueOnce(failure)
        .mockResolvedValueOnce(undefined)
    };
    const service = createDocumentProcessingService({ broker, repository });

    await expect(service.republishQueuedJobs()).resolves.toEqual({
      published: 1,
      failures: [{ jobId, error: failure }]
    });
    expect(broker.publish).toHaveBeenCalledTimes(2);
  });

  it('publishes nothing when no queued jobs are available', async () => {
    const repository = createRepositoryDouble();
    const broker = createBrokerDouble();
    const service = createDocumentProcessingService({ broker, repository });

    await expect(service.republishQueuedJobs()).resolves.toEqual({
      published: 0,
      failures: []
    });
    expect(broker.publish).not.toHaveBeenCalled();
  });
});
